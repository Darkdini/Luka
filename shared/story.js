// Глава доступна, если пройдена предыдущая и хватает уровня Цитадели
export function chapterOpen(state, ch) {
  const castle = state.buildings.find((b) => b.type === 'castle')?.level || 1;
  const prevDone = ch.id === 1 || (state.story?.[ch.id - 1]?.stars > 0);
  return { open: prevDone && castle >= ch.castle, prevDone, castleOk: castle >= ch.castle };
}
